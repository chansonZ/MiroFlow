# run_internal – B-style fallback triggered
# ---------------------------------------------------------------------------

class TestRunInternalBStyle:
    @pytest.mark.asyncio
    async def test_b_style_writes_final_boxed(self):
        proc = _make_processor(b_response="## Final Answer\n\nThe answer is 42.")
        ctx = _make_ctx(
            final_boxed_answer="No final answer generated.",
            llm_extracted_final_answer="",
            task_description="What is 6*7?",
            message_history=[{"role": "assistant", "content": "6 * 7 = 42"}],
        )
        result = await proc.run_internal(ctx)

        # B-style: result should be written to final_boxed_answer
        assert result.get("final_boxed_answer") == "## Final Answer\n\nThe answer is 42."
        assert result.get("llm_extracted_final_answer") == "## Final Answer\n\nThe answer is 42."

    @pytest.mark.asyncio
    async def test_think_blocks_stripped_from_b_response(self):
        raw = "<think>inner</think>\n\nThe answer is Paris."
        proc = _make_processor(b_response=raw)
        ctx = _make_ctx(
            final_boxed_answer="",
            llm_extracted_final_answer="",
            task_description="Capital of France?",
            message_history=[],
        )
        result = await proc.run_internal(ctx)
        # think block should be removed
        assert "<think>" not in result.get("final_boxed_answer", "")
        assert "The answer is Paris." in result.get("final_boxed_answer", "")

    @pytest.mark.asyncio
    async def test_trailing_user_message_removed_before_call(self):
        proc = _make_processor(b_response="Fallback answer")
        ctx = _make_ctx(
            final_boxed_answer="",
            llm_extracted_final_answer="",
            task_description="Q?",
            message_history=[
                {"role": "assistant", "content": "Some response"},
                {"role": "user", "content": "Follow-up question"},
            ],
        )
        await proc.run_internal(ctx)

        # Check the messages passed to LLM - user's trailing message should be removed
        call_args = proc.llm_client.create_message.call_args
        if call_args.args:
            sent_history = call_args.args[0]
        else:
            sent_history = call_args.kwargs["message_history"]

        user_followup = [
            m for m in sent_history
            if m.get("role") == "user" and "Follow-up" in str(m.get("content", ""))
        ]
        assert len(user_followup) == 0


# ---------------------------------------------------------------------------
# run_internal – A-style fallback when B fails
# ---------------------------------------------------------------------------

class TestRunInternalAStyleFallback:
    @pytest.mark.asyncio
    async def test_a_style_when_b_returns_empty(self):
        proc = object.__new__(FallbackFinalAnswerGenerator)
        pm = MagicMock()
        pm.render_prompt = MagicMock(return_value="summarise please")
        proc.prompt_manager = pm

        llm = MagicMock()
        # First call (B-style) returns empty; second call (A-style) returns content
        empty_resp = MagicMock()
        empty_resp.response_text = ""
        a_resp = MagicMock()
        a_resp.response_text = "Failure type: incomplete\nWhat happened: ran out of turns"
        llm.create_message = AsyncMock(side_effect=[empty_resp, a_resp])
        proc.llm_client = llm

        ctx = _make_ctx(
            final_boxed_answer="",
            llm_extracted_final_answer="",
            task_description="Some task",
            message_history=[],
        )
        result = await proc.run_internal(ctx)

        # A-style result should be written to summary as well
        assert result.get("summary") is not None
        assert result.get("final_boxed_answer") is not None

    @pytest.mark.asyncio
    async def test_a_style_when_b_raises_context_limit(self):
        proc = object.__new__(FallbackFinalAnswerGenerator)
        pm = MagicMock()
        pm.render_prompt = MagicMock(return_value="prompt")
        proc.prompt_manager = pm

        llm = MagicMock()
        a_resp = MagicMock()
        a_resp.response_text = "Failure type: blocked\nWhat happened: context limit"
        llm.create_message = AsyncMock(side_effect=[ContextLimitError("too long"), a_resp])
        proc.llm_client = llm

        ctx = _make_ctx(
            final_boxed_answer="",
            llm_extracted_final_answer="",
            task_description="Some task",
            message_history=[{"role": "assistant", "content": "some content"}],
        )
        result = await proc.run_internal(ctx)

        # Should fall through to A-style
        assert result.get("final_boxed_answer") is not None or result.get("summary") is not None

    @pytest.mark.asyncio
    async def test_context_limit_in_a_style_returns_static_message(self):
        proc = object.__new__(FallbackFinalAnswerGenerator)
        pm = MagicMock()
        pm.render_prompt = MagicMock(return_value="prompt")
        proc.prompt_manager = pm

        llm = MagicMock()
        # Both B-style and A-style raise ContextLimitError
        llm.create_message = AsyncMock(
            side_effect=[ContextLimitError("too long"), ContextLimitError("too long")]
        )
        proc.llm_client = llm

        ctx = _make_ctx(
            final_boxed_answer="",
            llm_extracted_final_answer="",
            task_description="Some task",
            message_history=[],
        )
        result = await proc.run_internal(ctx)

        # A-style ContextLimitError produces a static message
        final = result.get("final_boxed_answer") or result.get("summary") or ""
        assert "context" in final.lower() or "limit" in final.lower()


